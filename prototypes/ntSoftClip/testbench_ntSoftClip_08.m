paramState.oversampling_mode = plugin.oversampling_mode;
end

function val = fromNormalizedg_clip_db(normval)
val = -40 + (40--40)*normval;
end

function val = fromNormalizedsymmetry_procent(normval)
val = 50 + (100-50)*normval;
end

function val = fromNormalizeddc_offset(normval)
val = -1 + (1--1)*normval;
end

function val = fromNormalizedsquare_clip(normval)
val = logical(floor(0.5 + normval));
end

function val = fromNormalizedg_db(normval)
val = -24 + (24--24)*normval;
end

function val = fromNormalizedbypass(normval)
val = logical(floor(0.5 + normval));
end

function val = fromNormalizedoversampling_mode(normval)
enums = [ oversamplingEnum.disable oversamplingEnum.iir_2x oversamplingEnum.iir_4x oversamplingEnum.iir_8x oversamplingEnum.fir_2x_lq oversamplingEnum.fir_4x_lq oversamplingEnum.fir_8x_lq oversamplingEnum.fir_2x_hq oversamplingEnum.fir_4x_hq oversamplingEnum.fir_8x_hq ];
val = enums(1 + floor( 0.5 + normval * (numel(enums)-1)));
end
