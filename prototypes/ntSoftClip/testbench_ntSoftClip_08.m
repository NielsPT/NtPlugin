function checkForTampering(plugin, paramState, sampleRate, cause)
% Verify parameters were not tampered with
if ~isequal(paramState.g_clip_db, plugin.g_clip_db)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''g_clip_db'' from %g to %g.', ...
        cause, paramState.g_clip_db, plugin.g_clip_db);
end
if ~isequal(paramState.symmetry_procent, plugin.symmetry_procent)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''symmetry_procent'' from %g to %g.', ...
        cause, paramState.symmetry_procent, plugin.symmetry_procent);
end
if ~isequal(paramState.dc_offset, plugin.dc_offset)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''dc_offset'' from %g to %g.', ...
        cause, paramState.dc_offset, plugin.dc_offset);
end
if ~isequal(paramState.square_clip, plugin.square_clip)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''square_clip'' from %g to %g.', ...
        cause, paramState.square_clip, plugin.square_clip);
end
if ~isequal(paramState.g_db, plugin.g_db)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''g_db'' from %g to %g.', ...
        cause, paramState.g_db, plugin.g_db);
end
if ~isequal(paramState.bypass, plugin.bypass)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''bypass'' from %g to %g.', ...
        cause, paramState.bypass, plugin.bypass);
end
if ~isequal(paramState.oversampling_mode, plugin.oversampling_mode)
    error('ValidateAudioPlugin:ParamChanged', ...
        '%s changed parameter ''oversampling_mode''.', cause);
end
% Verify sample rate was not tampered with
if ~isequal(getSampleRate(plugin), sampleRate)
    error('ValidateAudioPlugin:SampleRateChanged', ...
        '%s changed sample rate from %g to %g.', ...
        cause, sampleRate, getSampleRate(plugin));
end
end

function y = logchirp(f0, f1, Fs, nsamples, initialPhase)
% logarithmically swept sine from f0 to f1 over nsamples, at Fs
y = zeros(nsamples,numel(initialPhase));
instPhi = logInstantaneousPhase(f0, f1, Fs, nsamples);
for i = 1:numel(initialPhase)
    y(:,i) = sin(instPhi + initialPhase(i));
end
end

function phi = logInstantaneousPhase(f0, f1, Fs, n)
final = n-1;
t = (0:final)/final;
t1 = final/Fs;
phi = 2*pi * t1/log(f1/f0) * (f0 * (f1/f0).^(t') - f0);
end

