    function y = process(p, x)
      n = length(x);
      y = zeros(n, 2);
      lLoc = [0 0];
      y_est = 0;
      x_m = zeros(p.m + 1, 1);
      n_mod = [0, 0];

      % n_mod = [p.state(5), p.state(6)];
      % y_rect_1 = p.state(1);
      % y_rect_2 = p.state(2);
      % y_diff_1 = p.state(3);
      % y_diff_2 = p.state(4);
      % y_avg_1 = p.state(7);
      % y_diff_smooth_1 = p.state(8);
      % sum_diff = p.state(9);

      x(~isreal(x)) = 0;

      if (p.bypass == true)
        y = x;
      else
        for i = 1:n
          p.dLine(p.store_loc, :) = x(i, :);

          if (p.trigged == true)
            % % LPF
            % y_lpf = p.a_lpf1 * x(i, :) + (1 - p.a_lpf1) * p.st_lpf1;
            % p.st_lpf1 = y_lpf;

            % % rectify and smooth
            % y_rect = max(max(abs(y_lpf)), p.a_rect * y_rect_1 + ...
            %    (1 - p.a_rect) * max(abs(y_lpf)));

            % % Take average
            % y_avg = p.a_avg * y_rect + (1 - p.a_avg) * y_avg_1;
            % y_avg_1 = y_avg;

            % % differentiate
            % y_diff = y_rect - y_rect_2;

            % % store state
            % y_rect_2 = y_rect_1;
            % y_rect_1 = y_rect;

            % % compare
            % if (y_diff > y_diff_1) && (y_diff > 0)
            %    sum_diff = sum_diff + y_diff;
            % else
            %    sum_diff = 0;
            % end
            % y_norm = sum_diff; % / y_avg;

            % trig = false;
            % if y_norm > p.sens
            %    if p.samplesSinceTrig > p.n_reTrig
            %       trig = true;
            %       p.samplesSinceTrig = 0;
            %    end
            % end
            % p.samplesSinceTrig = p.samplesSinceTrig + 1;

            % % store state
            % y_diff_2 = y_diff_1;
            % y_diff_1 = y_diff;

            if i > p.m
              % make new x_m-vector
              x_m = flip(p.rnd((i - p.m):i));

              % filter input with adaptive filter
              y_est = p.w(:, i)' * x_m;
            end

            % calculate error
            e = x(i) - y_est;

            % calculate coefficients for the next iteration
            if i ~= n
              p.w(:, (i + 1)) = p.w(:, i) + p.mu_0 / (x_m' * x_m) * x_m;
              if isnan(p.w(:, (i + 1))) == true
                p.w(:, (i + 1)) = 0;
              end
            end

            trig = false;
            if e > p.sens
              if p.samplesSinceTrig > p.n_reTrig
                trig = true;
                p.samplesSinceTrig = 0;
              end
            end
            p.samplesSinceTrig = p.samplesSinceTrig + 1;

            % calculate delay
            if trig == true
              if p.triple == false
                n_mod(1) = 0;
              else
                n_mod(1) = round((p.rnd(n - i) * 2 - 1) * p.n_delay * p.modDepth) + p.n_delay;
              end
              n_mod(2) = round((p.rnd(i) * 2 - 1) * p.n_delay * p.modDepth) + p.n_delay;
              % disp("trigged") %, diff = " + num2str(y_norm) + ", t_mod = " + num2str(n_mod ./ p.fs));
            end

          else % Trigged
            % calculate modulated delay time
            n_mod(1) = round(saw(2 .* pi .* p.modFreq ./ p.fs .* p.tCount) .* ...
              p.n_delay .* p.modDepth) + p.n_delay;
            n_mod(2) = round(saw(2 .* pi .* p.modFreq ./ p.fs .* p.tCount + ...
              p.modPhase * pi / 180) .* p.n_delay .* p.modDepth) + p.n_delay;
            p.tCount = p.tCount + 1;
          end

          lLoc(1) = p.store_loc - n_mod(1);
          if (lLoc(1) < 1)
            lLoc(1) = lLoc(1) + p.len_delayLine;
          end
          lLoc(2) = p.store_loc - n_mod(2);
          if (lLoc(2) < 1)
            lLoc(2) = lLoc(2) + p.len_delayLine;
          end

          if p.triple == true
            y(i, 1) = p.mix .* p.dLine(lLoc(1), 1) + (1 - p.mix) .* x(i, 1);
            y(i, 2) = p.mix .* p.dLine(lLoc(2), 2) + (1 - p.mix) .* x(i, 2);
          else
            y(i, 1) = x(i, 1);
            y(i, 2) = p.dLine(lLoc(2), 2);
          end
          p.store_loc = p.store_loc + 1;
          p.store_loc(p.store_loc > p.len_delayLine) = 1;
        end
      end
      % p.state = [y_rect_1; y_rect_2; y_diff_1; y_diff_2; ...
      % n_mod(1); n_mod(2); y_avg_1; y_diff_smooth_1; sum_diff];
      % p.state = [0; 0; 0; 0; ...
