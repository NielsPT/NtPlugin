    end
    function y = saw(x)
      % x   y
      % 0 ~ 0
      % pi/2 ~ 1
      % pi ~ 0
      % 3pi/2 ~ -1

      n = length(x);
      y = zeros(n, 1);
      for i = 1:n
        x_ = mod(x(i), 2 * pi);
        if x_ < 0
          x_ = x_ + 2 * pi;
        end

        alpha = 2 / pi;

        if x_ < pi / 2
          y_ = x_ * alpha;
        elseif x_ < 3 * pi / 2
          y_ = -x_ * alpha + 2;
        else
          y_ = x_ * alpha - 4;
        end
        y(i) = y_;
      end
    end
